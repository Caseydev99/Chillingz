/* ==========================================================================
   utils.js — small helpers shared by all the other scripts
   --------------------------------------------------------------------------
   Nothing here draws a page by itself. These are tools the other files use:
   safe browser storage, making text safe for HTML, pop-up messages (toasts)
   and the icon drawings.
   ========================================================================== */


/* Safe browser storage. Some browsers (private mode, blocked cookies) refuse
   to store anything; these helpers quietly carry on instead of crashing. */
export const storage = {
  get(key, fallback = null) {
    try {
      const value = localStorage.getItem(key);
      return value === null ? fallback : JSON.parse(value);
    } catch {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch {
      /* storage not available — nothing to do */
    }
  },
  remove(key) {
    try {
      localStorage.removeItem(key);
    } catch {
      /* storage not available — nothing to do */
    }
  },
};

/* Makes text safe to put inside HTML, so a name like "<b>" shows as text
   instead of being treated as code. Use it for anything that came from a
   visitor or the database. */
export function escapeHtml(text) {
  return String(text ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

/* Shows a short message at the bottom of the screen for a few seconds,
   e.g. "Saved to favourites". Screen readers read it out too. */
let toastTimer = null;
export function showToast(message) {
  let toast = document.getElementById("toast");
  if (!toast) {
    toast = document.createElement("div");
    toast.id = "toast";
    toast.className = "toast";
    toast.setAttribute("role", "status");
    toast.setAttribute("aria-live", "polite");
    document.body.append(toast);
  }
  toast.textContent = message;
  toast.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => {
    toast.hidden = true;
  }, 3500);
}

